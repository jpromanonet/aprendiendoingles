"""Clases temáticas del inglés británico (England). Doce por nivel; aquí van A1 (base), A2, B1 y B2.

Cada clase trae sus propias palabras: el léxico del nivel sale de ahí, así que
cada palabra queda anclada (pin) en la clase donde se enseña.
El campo «hanzi» del léxico guarda la palabra en inglés y «pinyin», su guía de pronunciación.
"""

from en_pron import pron, register


def w(en, es, ex, ex_es, pr=None):
    """Palabra, español, ejemplo, traducción y (opcional) pronunciación a mano."""
    return (en, es, ex, ex_es, pr)


def L(title, summary, body, words, dialogue=None, quiz=None, reuse=()):
    for item in words:
        if len(item) > 4 and item[4]:
            register(item[0], item[4])
    return {
        "title": title,
        "summary": summary,
        "body": body,
        "words": words,
        "reuse": list(reuse),
        "dialogue": dialogue,
        "quiz": quiz,
    }


def D(*pairs):
    """Diálogo: pares (inglés, español). La guía de pronunciación sale sola."""
    return [{"zh": en, "py": pron(en), "es": es} for en, es in pairs]


def Q(prompt, right, *wrong):
    """Pregunta de opción múltiple; la correcta va primera (el sitio mezcla las opciones)."""
    return {"prompt": prompt, "options": [right, *wrong], "correct": 0}


def row(item, level):
    en, es, ex, ex_es = item[:4]
    pr = item[4] if len(item) > 4 and item[4] else pron(en)
    return {
        "hanzi": en,
        "pinyin": pr,
        "es": es,
        "level": level,
        "ex_zh": ex,
        "ex_py": pron(ex),
        "ex_es": ex_es,
    }


def bind(specs, level):
    """Devuelve (filas de léxico, clases numeradas) a partir de las clases de un nivel."""
    rows, lessons = [], []
    for number, spec in enumerate(specs, 1):
        rows += [row(item, level) for item in spec["words"]]
        pins = [item[0] for item in spec["words"]] + spec["reuse"]
        dialogue = spec["dialogue"]
        if dialogue:
            dialogue = [{**line, "py": pron(line["zh"])} for line in dialogue]
        lesson = {
            "number": number,
            "title": spec["title"],
            "summary": spec["summary"],
            "body": spec["body"],
            "pins": pins,
        }
        if dialogue:
            lesson["dialogue"] = dialogue
        if spec["quiz"]:
            lesson["quiz"] = spec["quiz"]
        lessons.append(lesson)
    return rows, lessons


